# matematika di python
a = 10
b = 3

# penjumlahan
print(a + b) #perjumlahan biasa

# pengurangan
print(a - b) 

# perkalian
print(a * b) 

# pembagian biasa
print(a / b)

# pembagian yang di bulatkan
print(a // b) #jika dibawah 5 dibulatkan ke bawah, jika diatas 5 dibulatkan ke atas

# modulus
print(a % b) #sisa bagi

#kuadrat
print(a ** b)

# 
print(100 + 40 * 5 / (10 - 4)) #urutan operasi matematika, kurung, perkalian, pembagian, penjumlahan, pengurangan

